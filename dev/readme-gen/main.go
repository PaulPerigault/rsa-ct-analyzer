// Command readme-gen keeps the sample output of README.md equal to what the
// CLI really prints. Run from the repository root.
//
//	go run ./dev/readme-gen          rewrite the block between the markers
//	go run ./dev/readme-gen -check   exit 1 if README.md differs
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/PaulPerigault/rsa-ct-analyzer/internal/analyze"
	"github.com/PaulPerigault/rsa-ct-analyzer/internal/keys"
	"github.com/PaulPerigault/rsa-ct-analyzer/internal/report"
)

const (
	readme = "README.md"
	begin  = "<!-- BEGIN scan-output (generated by `task docs:readme`, do not edit) -->"
	end    = "<!-- END scan-output -->"

	command = "rsa-ct-analyzer scan testdata/certs --min-severity medium"
)

func main() {
	check := flag.Bool("check", false, "fail if README.md is not up to date")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "readme-gen:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	block, err := render()
	if err != nil {
		return err
	}
	current, err := os.ReadFile(readme)
	if err != nil {
		return err
	}
	updated, err := replaceBlock(string(current), block)
	if err != nil {
		return err
	}
	if check {
		if updated != string(current) {
			return fmt.Errorf("%s is out of date: run `task docs:readme`", readme)
		}
		return nil
	}
	return os.WriteFile(readme, []byte(updated), 0o644) //nolint:gosec // documentation file
}

// render runs the same code path as `scan`, with fixed options.
func render() (string, error) {
	loaded := keys.Load([]string{"testdata/certs"}, nil)
	if len(loaded.Errors) > 0 {
		return "", loaded.Errors[0]
	}
	opt := analyze.Defaults()
	opt.Workers = 1
	opt.Now = func() time.Time { return time.Date(2026, 11, 12, 0, 0, 0, 0, time.UTC) }
	rep, err := analyze.Analyze(context.Background(), loaded.Keys, loaded.Skipped, opt)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := report.Write(&buf, rep, report.Table, analyze.Medium); err != nil {
		return "", err
	}
	return "```console\n$ " + command + "\n" + buf.String() + "```", nil
}

func replaceBlock(doc, block string) (string, error) {
	i, j := strings.Index(doc, begin), strings.Index(doc, end)
	if i < 0 || j < i {
		return "", fmt.Errorf("markers not found in %s", readme)
	}
	return doc[:i+len(begin)] + "\n" + block + "\n" + doc[j:], nil
}
